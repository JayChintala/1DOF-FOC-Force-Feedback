# -*- coding: utf-8 -*-
"""
Writes deck_outline.md: a plain-text mirror of
"Force-Aware Telepresence for Robot Learning.pptx" -- every slide's title,
text, tables, chart data (category values; XY series as point counts and
ranges), figures and speaker notes -- so the deck can be read, searched and
discussed without opening PowerPoint (e.g. by a Claude Code session).

Re-run after any change to the deck:   python3 export_deck_outline.py
Needs python-pptx.
"""
import os

from pptx import Presentation

HERE = os.path.dirname(os.path.abspath(__file__))
DECK = os.path.join(HERE, "Force-Aware Telepresence for Robot Learning.pptx")
OUT = os.path.join(HERE, "deck_outline.md")


def fmt(v):
    if v is None:
        return "—"
    if isinstance(v, float):
        return f"{v:.4g}"
    return str(v)


def chart_lines(chart):
    out = []
    title = chart.chart_title.text_frame.text if chart.has_title else "(untitled chart)"
    out.append(f"**Chart: {title}**")
    plot = chart.plots[0]
    try:
        cats = list(plot.categories)
    except Exception:
        cats = []
    if cats:
        out.append("")
        out.append("| series | " + " | ".join(str(c) for c in cats) + " |")
        out.append("|---" * (len(cats) + 1) + "|")
        for s in plot.series:
            out.append(f"| {s.name} | " + " | ".join(fmt(v) for v in s.values) + " |")
    else:                                        # XY: summarise, don't dump
        for s in plot.series:
            xs = [float(v) for v in s._element.xpath("./c:xVal//c:v/text()")]
            ys = [float(v) for v in s._element.xpath("./c:yVal//c:v/text()")]
            if ys:
                out.append(f"- {s.name}: {len(ys)} points, x {min(xs):.3g}…{max(xs):.3g}, "
                           f"y {min(ys):.3g}…{max(ys):.3g}")
    return out


def main():
    prs = Presentation(DECK)
    lines = [
        "# Deck outline: Force-Aware Telepresence for Robot Learning",
        "",
        "Generated by `export_deck_outline.py` from the .pptx in this folder — do not edit by hand; "
        "re-run it after changing the deck. Chart tables are the exact values plotted.",
        "",
    ]
    for i, slide in enumerate(prs.slides, 1):
        title = slide.shapes.title.text_frame.text.strip() if slide.shapes.title is not None else ""
        lines.append(f"## Slide {i}: {title or '(no title)'}")
        lines.append("")
        for sh in slide.shapes:
            if slide.shapes.title is not None and sh.shape_id == slide.shapes.title.shape_id:
                continue
            if sh.has_chart:
                lines += chart_lines(sh.chart) + [""]
            elif sh.has_table:
                tbl = sh.table
                rows = [[c.text.strip().replace("\n", " ") for c in r.cells] for r in tbl.rows]
                lines.append("| " + " | ".join(rows[0]) + " |")
                lines.append("|---" * len(rows[0]) + "|")
                for r in rows[1:]:
                    lines.append("| " + " | ".join(r) + " |")
                lines.append("")
            elif sh.shape_type == 13:                         # picture
                descr = sh._element.xpath("./p:nvPicPr/p:cNvPr/@descr")
                lines.append(f"*Figure: {sh.name}*" + (f" — {descr[0]}" if descr and descr[0] else ""))
                lines.append("")
            elif sh.has_text_frame and sh.text_frame.text.strip():
                for p in sh.text_frame.paragraphs:
                    t = p.text.strip()
                    if t:
                        lines.append(("- " if p.level or len(sh.text_frame.paragraphs) > 1 else "") + t)
                lines.append("")
        if slide.has_notes_slide:
            notes = slide.notes_slide.notes_text_frame.text.strip()
            if notes:
                nl = notes.split("\n")
                lines.append("> **Speaker notes:** " + nl[0])
                lines += [("> " + l) if l.strip() else ">" for l in nl[1:]]
                lines.append("")
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines))
    print("wrote", OUT, f"({len(prs.slides)} slides)")


if __name__ == "__main__":
    main()
